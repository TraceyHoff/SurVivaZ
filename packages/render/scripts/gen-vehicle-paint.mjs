#!/usr/bin/env node
// Folds the paint contract of Art's packages/assets/pack/vehicles/manifest.vehicles.json (vehicles[].tint + tintSets) into
// packages/render/src/vehicles/paint.data.ts. Run: node packages/render/scripts/gen-vehicle-paint.mjs
// The adr519 test fails when the generated module drifts from the manifest.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../../", import.meta.url));
export function paintTable(m) {
  const vehicles = {}; const used = new Set();
  for (const v of m.vehicles ?? []) { const t = v.tint; if (!t || t.mask !== "tintmask" || t.channel !== "r") continue;
    vehicles[v.sprite ?? v.key] = [t.tintSet, t.defaultIndex ?? 0, t.neutral ?? 1, t.strength ?? 1]; used.add(t.tintSet); }
  const sets = {}; for (const s of m.tintSets ?? []) if (used.has(s.key)) sets[s.key] = s.tints.map((c) => parseInt(c.slice(1), 16));
  return { sets, vehicles };
}
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const m = JSON.parse(readFileSync(root + "packages/assets/pack/vehicles/manifest.vehicles.json", "utf8"));
  const t = paintTable(m); const hex = (n) => "0x" + n.toString(16).padStart(6, "0");
  writeFileSync(root + "packages/render/src/vehicles/paint.data.ts", `/**
 * GENERATED by packages/render/scripts/gen-vehicle-paint.mjs from Art's packages/assets/pack/vehicles/manifest.vehicles.json
 * (vehicles[].tint, tintSets). Do not edit by hand: re-run the script.
 * Contract (Art): out = base * mix(1, color / neutral, strength * tintmask.r).
 * Per Art key: [tint set, default index, neutral, strength].
 */
export const VEHICLE_PAINT_SETS: Readonly<Record<string, readonly number[]>> = {
${Object.entries(t.sets).map(([k, v]) => `  ${k}: [${v.map(hex).join(", ")}],`).join("\n")}
};
export const VEHICLE_PAINT: Readonly<Record<string, readonly [string, number, number, number]>> = {
${Object.entries(t.vehicles).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}
};
`);
  console.log("wrote paint.data.ts", Object.keys(t.vehicles).length, "keys");
}
