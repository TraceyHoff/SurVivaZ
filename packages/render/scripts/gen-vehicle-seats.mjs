#!/usr/bin/env node
// Folds Art's packages/assets/pack/vehicles/seats.vehicles.json (not shipped to dist) into
// packages/render/src/vehicles/seats.data.ts at build time. Run: node packages/render/scripts/gen-vehicle-seats.mjs
// The adr518 test fails when the generated module drifts from the JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../../", import.meta.url));
export function seatTable(j) {
  const out = {};
  for (const [key, e] of Object.entries(j.vehicles)) {
    out[key] = { h: e.realSize.height, w: e.realSize.width, aliases: e.aliases ?? [], rearGlass: e.rearGlass === false ? 0 : 1, seats: e.seats.map((s) => [s.u, s.v, s.z, s.draw === "window" ? 1 : 0, s.window?.beltZ ?? 0, s.window?.roofZ ?? 0, s.cabin === false ? 0 : 1]) };
  }
  return out;
}
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const j = JSON.parse(readFileSync(root + "packages/assets/pack/vehicles/seats.vehicles.json", "utf8"));
  const t = seatTable(j);
  const body = Object.entries(t).map(([k, v]) => `  ${k}: { h: ${v.h}, w: ${v.w}, aliases: ${JSON.stringify(v.aliases)}, rearGlass: ${v.rearGlass}, seats: ${JSON.stringify(v.seats)} },`).join("\n");
  writeFileSync(root + "packages/render/src/vehicles/seats.data.ts", `/**
 * GENERATED by packages/render/scripts/gen-vehicle-seats.mjs from Art's packages/assets/pack/vehicles/seats.vehicles.json
 * (true-scale pass; that file does not ship to dist). Do not edit by hand: re-run the script.
 * Per Art key: h = real roof height, w = real width (m); rearGlass 0 = no rear window (a ray leaving through the rear
 * end hides the rider; default 1); seats = [u, v, z, draw, beltZ, roofZ, cabin] in metres, vehicle-local (u forward,
 * v = Art "right" = the engine's +v, z up = seat H-point); draw 0 = "over" (rider after the sprite), 1 = "window"
 * (rider after the sprite, clipped to the beltZ..roofZ band); cabin 1 = inside the cabin (default), 0 = outside it (an open-bed
 * seat: still clipped to its own beltZ..roofZ, but it does not extend the cabin box the window clip is measured against).
 */
export interface VehicleSeatArt { h: number; w: number; aliases: readonly string[]; rearGlass: 0 | 1; seats: readonly (readonly [number, number, number, 0 | 1, number, number, 0 | 1])[] }
export const PX_PER_M_HEIGHT = ${j.scale.pxPerMetreHeight};
export const PX_PER_M_LENGTH = ${j.scale.pxPerMetreLength};
export const PX_PER_M_DEPTH = ${j.scale.pxPerMetreDepth};
export const VEHICLE_SEAT_ART: Readonly<Record<string, VehicleSeatArt>> = {
${body}
};
`);
  console.log("wrote seats.data.ts", Object.keys(t).length, "keys");
}
