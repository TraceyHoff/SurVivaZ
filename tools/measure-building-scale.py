#!/usr/bin/env python3
"""ADR-504: measure every base building piece's drawn size from the art the game resolves (scale audit).

For each structural piece (pieces.json) and every tier it can be built at, the sprite is resolved like the client
(`<key>@tier<N>` first, else the bare key; manifests in MANIFEST_INDEX order, first definition wins) and its r0 intact
frame is measured at 1x, in px above the sprite pivot (pivot = ground point of the piece: the tile-edge midpoint for
edge pieces, the tile centre for cell / free pieces):
  topPx        highest opaque pixel (edge / opening pieces: inside the pivot column band +-4 px, i.e. the wall face
               over its own base, not the far end of the iso edge)
  openTopPx    wall openings (doorway / window / arch): top of the tallest clear opening within +-20 px of the pivot
  openSillPx   wall openings: bottom of the clear opening (0 = floor level, a walk-through doorway)
Writes packages/gameplay/data/building_scale.measured.json (the adr504_building_scale test reads it and checks the
atlas hashes, so stale numbers fail). Re-run after Art changes a building sprite: python3 tools/measure-building-scale.py
"""
import hashlib, json, os
from PIL import Image
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = f"{R}/packages/assets/pack"
ORDER = ["manifest.json", "building/manifest.building.json"]  # MANIFEST_INDEX order of the fragments that carry pieces
STRUCT = ("foundation", "floor", "wall", "pillar", "stairs", "door_", "hatch_wood", "window_", "ladder", "gate_clan",
          "clan_hall_door", "garden_gate", "fence_", "barricade_spiked", "shaft_hatch", "watchtower", "roof_")
spr, atl = {}, {}
for rel in ORDER:
    m = json.load(open(f"{PACK}/{rel}")); base = os.path.dirname(f"{PACK}/{rel}")
    for a in m.get("atlases", []): atl.setdefault(a["key"], {**a, "_base": base})
    for s in m.get("sprites", []):
        b = s.get("building")
        if b: spr.setdefault(b["piece"], s)
pieces = json.load(open(f"{R}/packages/gameplay/data/pieces.json"))["pieces"]
imgs, shas = {}, {}
def image(a):
    p = os.path.join(a["_base"], a["image"]); rel = os.path.relpath(p, R)
    if rel not in imgs: imgs[rel] = Image.open(p).convert("RGBA"); shas[rel] = hashlib.sha1(open(p, "rb").read()).hexdigest()
    return imgs[rel], rel
def frame(s):
    b = s["building"]; f = b["frames"][0]; return f[0] if isinstance(f, list) else f
def measure(s, edge, opening):
    a = atl[s["atlas"]]; im, rel = image(a); W, H, C = a["frameW"], a["frameH"], a["columns"]; fi = frame(s)
    al = im.crop(((fi % C) * W, (fi // C) * H, (fi % C) * W + W, (fi // C) * H + H)).getchannel("A").load()
    px, py = s["anchor"]["x"] * W, s["anchor"]["y"] * H
    cols = range(max(0, round(px) - 4), min(W, round(px) + 5)) if edge else range(W)
    op = lambda x, y: al[x, y] > 40
    top = min((y for x in cols for y in range(H) if op(x, y)), default=None)
    out = {"sprite": s["key"], "atlas": rel, "topPx": None if top is None else round(py - top, 1)}
    if opening:
        best = None
        for x in range(max(0, round(px) - 20), min(W, round(px) + 21)):  # +-20: a window mullion sits on the pivot column
            ys = [y for y in range(H) if op(x, y)]
            if len(ys) < 2: continue
            run = None
            for y in range(ys[0], ys[-1]):
                if not op(x, y): run = (run[0], y) if run and run[1] == y - 1 else (y, y)
                if run and (best is None or run[1] - run[0] > best[1] - best[0]): best = run
        if best: out["openTopPx"] = round(py - best[0], 1); out["openSillPx"] = max(0.0, round(py - best[1] - 1, 1))
    return out
res = {}
for p in pieces:
    k = p["key"]
    if not k.startswith(STRUCT) or p.get("$decor") and not k.startswith(("fence_", "garden_gate")): continue
    edge = p["placement"] in ("edge", "opening")
    opening = p.get("opening") in ("door", "window") or k == "wall_arched"
    tiers = range(p.get("minTier", 0), 5) if p.get("tiered") else [None]
    row = {}
    for t in tiers:
        s = (spr.get(f"{k}@tier{t}") if t else None) or spr.get(k)
        if s: row["t" + str(t) if t is not None else "fixed"] = measure(s, edge, opening)
    if row: res[k] = {"placement": p["placement"], **({"opening": p["opening"]} if p.get("opening") else {}), "tiers": row}
out = {"$comment": "ADR-504: generated by tools/measure-building-scale.py from the art (px above the pivot at 1x). Do not edit.",
       "atlasSha1": dict(sorted(shas.items())), "pieces": res}
json.dump(out, open(f"{R}/packages/gameplay/data/building_scale.measured.json", "w"), indent=1)
print(len(res), "pieces;", len(shas), "atlases")
